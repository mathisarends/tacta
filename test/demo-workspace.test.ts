import { afterEach, expect, it } from "vitest";
import { DemoWorkspace } from "../examples/chatbot/demo-workspace.js";
afterEach(() => document.body.replaceChildren());
it("opens surfaces, switches, reorders and closes tabs back to the picker", async () => {
  const panel = new DemoWorkspace();
  document.body.append(panel);
  await panel.updateComplete;
  const picker = panel.shadowRoot!.querySelector("tacta-surface-picker")!;
  await picker.updateComplete;
  picker.shadowRoot!.querySelector<HTMLButtonElement>("button")!.click();
  await panel.updateComplete;
  const bar = panel.shadowRoot!.querySelector("tacta-workspace-tab-bar")!;
  expect(bar.tabs[0]!.surface).toBe("Browser");
  expect(panel.shadowRoot!.querySelector("iframe")!.getAttribute("sandbox")).toBe("");
  bar.dispatchEvent(new CustomEvent("surface-open", { detail: "Terminal" }));
  await panel.updateComplete;
  const terminal = bar.active!;
  const browser = bar.tabs[0]!.id;
  expect(bar.tabs).toHaveLength(2);
  bar.dispatchEvent(new CustomEvent("tab-move", { detail: { id: terminal, index: 0 } }));
  await panel.updateComplete;
  expect(bar.tabs[0]!.id).toBe(terminal);
  bar.dispatchEvent(new CustomEvent("tab-select", { detail: browser }));
  await panel.updateComplete;
  expect(bar.active).toBe(browser);
  bar.dispatchEvent(new CustomEvent("tab-close", { detail: browser }));
  await panel.updateComplete;
  expect(bar.active).toBe(terminal);
  bar.dispatchEvent(new CustomEvent("tab-close", { detail: terminal }));
  await panel.updateComplete;
  expect(panel.shadowRoot!.querySelector("tacta-surface-picker")).not.toBeNull();
});
